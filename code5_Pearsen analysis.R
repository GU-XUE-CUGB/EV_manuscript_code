# --- Standardize data ----
df_all <- df_all %>%
  group_by(group) %>%
  mutate(rate_standardized = scale(rate)) %>%  # Standardize rate
  ungroup()

# Split data by group
result_list <- df_all %>%
  group_split(group)

# Preserve merge order (ensure output matches input order)
input_order <- unique(df_all$group)

# Name split results to ensure correspondence
group_names <- df_all %>%
  group_by(group) %>%
  group_keys() %>%
  pull(group)

names(result_list) <- group_names

# Compute linear fit and confidence interval for each group, calculate Pearson correlation
fit_and_predict <- function(df_sub){
  fit <- lm(rate_standardized ~ ev_aligned, data = df_sub)
  pred <- predict(fit, interval = "confidence")
  df_sub <- cbind(df_sub, pred)
  # Store fitted values in the data frame
  df_sub$fit_values <- fit$fitted.values
  list(data = df_sub, cor = cor(df_sub$rate_standardized, df_sub$ev_aligned, method = "pearson"))
}

result_fits <- map(result_list, fit_and_predict)

# Merge predicted data for plotting
df_plot <- bind_rows(lapply(result_fits, function(x) x$data))

# Compute correlation coefficients and p-values for each group, ordered by input sequence
cor_values_and_pvalues <- sapply(result_fits, function(x) {
  cor_test <- cor.test(x$data$rate_standardized, x$data$ev_aligned, method = "pearson")
  cor_val <- cor_test$estimate  # correlation coefficient
  p_value <- cor_test$p.value  # p-value
  # Return formatted correlation and p-value
  paste0(round(cor_val, 4), " (p = ", format.pval(p_value), ")")
})

# Arrange by input order and print
cor_values_and_pvalues <- cor_values_and_pvalues[input_order]

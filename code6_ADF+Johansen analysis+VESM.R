# 1. Interpolate EV to match Rate time points
EV_interp <- approx(x = T1, y = EV, xout = T2)$y
EV_interp <- na.approx(EV_interp)  # Fill missing values using interpolation

# 2. ADF test and determine integration order
get_order <- function(data, max_diff = 5) {
  order <- 0
  for (i in 1:max_diff) {
    # Perform ADF test
    adf_result <- ur.df(data, type = "none", selectlags = "AIC")
    # If series is stationary, return current differencing order
    if (adf_result@teststat < adf_result@cval[1, 2]) {
      return(order)  # Series is stationary
    } else {
      # Difference the series if not stationary
      data <- diff(data)
      order <- order + 1
    }
  }
  # Return max differencing if still non-stationary
  return(order)
}

# Determine integration order for EV and Rate
ev_order <- get_order(EV_interp)
rate_order <- get_order(Rate)

cat("Integration order of EV:", ev_order, "\n")
cat("Integration order of Rate:", rate_order, "\n")

# 3. Differencing to ensure both series are I(1)
if (ev_order == 1) {
  EV_diff <- EV_interp  # Already I(1)
} else {
  EV_diff <- diff(EV_interp, differences = ev_order - 1)
}

if (rate_order == 1) {
  Rate_diff <- Rate  # Already I(1)
} else {
  Rate_diff <- diff(Rate, differences = rate_order - 1)
}

# 4. Align differenced series length
if (length(EV_diff) > length(Rate_diff)) {
  EV_diff <- EV_diff[1:length(Rate_diff)]
} else if (length(Rate_diff) > length(EV_diff)) {
  Rate_diff <- Rate_diff[1:length(EV_diff)]
}

# Create aligned data frame
aligned_data <- data.frame(Time = T2[1:length(EV_diff)], EV = EV_diff, Rate = Rate_diff)
summary(aligned_data)

# 5. Cointegration test
coint_test <- ca.jo(aligned_data[, c("EV", "Rate")], type = "trace", ecdet = "none", spec = "longrun")
summary(coint_test)

# Assume r = 1, estimate VECM
vecm <- cajorls(coint_test, r = 1)

# Output VECM results
summary(vecm$rlm)

# Extract error correction coefficients
alpha_ev_rate <- vecm$rlm$coef[1]  # EV adjustment coefficient for Rate
alpha_rate_ev <- vecm$rlm$coef[5]  # Rate adjustment coefficient for EV

